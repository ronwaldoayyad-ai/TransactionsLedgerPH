import {test,expect} from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'

test('Borderless login keeps compact inputs, validation above email and protected motion',async({page},info)=>{
  test.setTimeout(120000)
  await page.emulateMedia({reducedMotion:'no-preference'})
  const artworkResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/assets/login-reference.png'&&r.status()===200)
  await page.goto('/login')
  const iframe=page.locator('iframe[title="LoanLedger PH · v4.12.24"]')
  const ui=await(await iframe.elementHandle()).contentFrame()
  await ui.waitForFunction(()=>!!document.querySelector('#loginEmailFeedback')&&!document.body.inert)
  await artworkResponse
  const animation=ui.frameLocator('.login-artwork-player')
  await expect(animation.locator('[data-engine="remotion"]')).toHaveAttribute('data-playing','true',{timeout:20000})
  await expect(ui.locator('.login-reference-artwork')).toHaveClass(/has-remotion/)
  await expect(animation.locator('button')).toHaveCount(0)
  await expect(ui.locator('.loginhero h1>.loginlogo')).toBeVisible()
  const artwork=animation.locator('svg[data-frame]')
  const beforeFrame=Number(await artwork.getAttribute('data-frame'))
  const beforePixels=crypto.createHash('sha256').update(await artwork.screenshot()).digest('hex')
  await expect.poll(async()=>Math.abs(Number(await artwork.getAttribute('data-frame'))-beforeFrame),{timeout:15000}).toBeGreaterThanOrEqual(25)
  const afterPixels=crypto.createHash('sha256').update(await artwork.screenshot()).digest('hex')
  expect(afterPixels).not.toBe(beforePixels)
  await expect(ui.locator('.login-protected svg')).toHaveCSS('animation-name','none')
  await ui.evaluate(()=>document.querySelector('#app').scrollTop=0)
  expect(await ui.locator('.login-reference-artwork').evaluate(el=>el.getBoundingClientRect().top)).toBeGreaterThanOrEqual(0)
  await expect(ui.locator('.modern-login-panel')).toHaveCSS('border-top-width','0px')
  await expect(ui.locator('.modern-login-panel')).toHaveCSS('box-shadow','none')
  expect(await ui.locator('.loginlogo').evaluate(el=>getComputedStyle(el,'::before').animationName)).toBe('loginLogoShine')
  expect(await ui.locator('.loginlogo').evaluate(el=>getComputedStyle(el,'::after').animationName)).toBe('loginSparkle')
  const footer=await ui.locator('.footer').textContent()
  for(const width of [320,390]){
    await page.setViewportSize({width,height:844})
    await ui.locator('#email').fill('invalid')
    await expect(ui.locator('#loginEmailFeedback')).toHaveText('Enter a valid email address.')
    for(const value of ['invalid','valid@example.com']){
      await ui.locator('#email').fill(value)
      const layout=await ui.evaluate(()=>{const email=document.querySelector('#email').closest('.login-field-control').getBoundingClientRect(),password=document.querySelector('#password').closest('.login-field-control').getBoundingClientRect(),feedback=document.querySelector('#loginEmailFeedback').getBoundingClientRect(),protectedBadge=document.querySelector('.login-protected').getBoundingClientRect();return {feedbackGap:email.top-feedback.bottom,inputGap:password.top-email.bottom,protectedGap:protectedBadge.top-password.bottom,overflow:document.documentElement.scrollWidth>innerWidth}})
      expect(layout.feedbackGap).toBeGreaterThanOrEqual(5)
      expect(layout.inputGap).toBeGreaterThanOrEqual(11)
      expect(layout.inputGap).toBeLessThanOrEqual(13)
      expect(layout.protectedGap).toBeGreaterThanOrEqual(5)
      expect(layout.overflow).toBe(false)
    }
    await expect(ui.locator('#loginEmailFeedback')).toHaveText('Email format looks valid.')
  }
  await ui.locator('#password').fill('Example-only-password')
  await ui.locator('#loginPasswordToggle').click()
  await expect(ui.locator('#password')).toHaveAttribute('type','text')
  await expect(ui.locator('#loginSignIn')).toBeEnabled()
  await ui.locator('#loginPasswordToggle').click()
  await expect(ui.locator('.login-protected svg')).toHaveCSS('animation-name','loginProtectionPulse')
  const badge=ui.locator('.login-protected')
  await expect(badge).toHaveAttribute('data-state','ready')
  await expect(badge).toHaveCSS('background-color','rgb(209, 250, 229)')
  await expect(badge.locator('.login-protected-check')).toHaveCSS('opacity','1')
  await expect(badge.locator('[role="status"]')).toHaveText('Sign-in fields are ready.')
  expect(await badge.evaluate(el=>getComputedStyle(el,'::before').animationName)).toBe('loginProtectionHalo')
  const firstShieldTransform=await badge.locator('svg').evaluate(el=>getComputedStyle(el).transform)
  await expect.poll(()=>badge.locator('svg').evaluate(el=>getComputedStyle(el).transform)).not.toBe(firstShieldTransform)
  await ui.locator('#email').fill('invalid')
  await expect(badge).toHaveAttribute('data-state','idle')
  await expect(badge.locator('svg')).toHaveCSS('animation-name','none')
  await ui.locator('#email').fill('valid@example.com')
  await ui.locator('#email').fill('')
  await expect(ui.locator('.login-protected svg')).toHaveCSS('animation-name','none')
  await ui.locator('#email').fill('valid@example.com')
  await expect(ui.locator('.login-protected svg')).toHaveCSS('animation-name','loginProtectionPulse')
  await ui.locator('#loginMethodToken').click()
  await expect(ui.locator('#loginTokenFields')).toBeVisible()
  await ui.locator('#loginMethodEmail').click()
  await expect(ui.locator('#email')).toHaveValue('valid@example.com')
  await expect(ui.locator('.footer')).toHaveText(footer)
  await expect(ui.getByRole('button',{name:/Need help logging in/})).toBeVisible()
  await ui.locator('#password').fill('')
  await expect(ui.locator('.login-protected svg')).toHaveCSS('animation-name','none')
  await ui.evaluate(()=>document.querySelector('#app').scrollTop=0)
  const dir=path.resolve(process.env.LOGIN_UI_EVIDENCE_DIR||'test-results/login-ui')
  fs.mkdirSync(dir,{recursive:true})
  await page.screenshot({path:path.join(dir,info.project.name+'-login.png'),fullPage:true})
  // Simulate password manager fills that emit neither input nor change events.
  await ui.evaluate(()=>{document.querySelector('#email').value='autofill@example.com';document.querySelector('#password').value='Example-only-password'})
  await expect(badge).toHaveAttribute('data-state','ready')
  await expect(ui.locator('#loginSignIn')).toBeEnabled()
  await page.screenshot({path:path.join(dir,info.project.name+'-protected-ready.png'),fullPage:true})
  await ui.evaluate(()=>document.querySelector('#password').value='')
  await expect(badge).toHaveAttribute('data-state','idle')
  await expect(ui.locator('#loginSignIn')).toBeDisabled()
  await ui.locator('#password').fill('Example-only-password')
  await page.emulateMedia({reducedMotion:'reduce'})
  await expect(ui.locator('.login-protected svg')).toHaveCSS('animation-name','none')
  await expect(badge).toHaveAttribute('data-state','ready')
  await expect(badge).toHaveCSS('background-color','rgb(209, 250, 229)')
  await expect(badge.locator('.login-protected-check')).toHaveCSS('stroke-dashoffset','0px')
  await expect(animation.locator('[data-engine="remotion"]')).toHaveAttribute('data-motion','gentle')
  await expect(animation.locator('[data-engine="remotion"]')).toHaveAttribute('data-playing','true')
  const gentleFrame=Number(await artwork.getAttribute('data-frame'))
  await expect.poll(async()=>Math.abs(Number(await artwork.getAttribute('data-frame'))-gentleFrame),{timeout:15000}).toBeGreaterThanOrEqual(15)
  await expect(animation.locator('button')).toHaveCount(0)
  await ui.evaluate(()=>document.body.classList.add('dark'))
  await expect(ui.locator('.modern-login-panel')).toHaveCSS('border-top-width','0px')
  await expect(ui.locator('.modern-login-panel')).toHaveCSS('background-color','rgba(0, 0, 0, 0)')
})
